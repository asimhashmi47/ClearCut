// Writes the SHA-256 of every file in public/models to src/lib/modelHashes.ts.
// Run this whenever a model file is added or replaced.
import { createHash } from 'node:crypto'
import { readdir, readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'

const MODELS_DIR = 'public/models'
const OUTPUT = 'src/lib/modelHashes.ts'

const entries = await readdir(MODELS_DIR, { recursive: true, withFileTypes: true })
const files = entries
  .filter((entry) => entry.isFile())
  .map((entry) => path.relative(MODELS_DIR, path.join(entry.parentPath, entry.name)).replaceAll('\\', '/'))
  .sort()

const lines = await Promise.all(
  files.map(async (file) => `  '${file}': '${createHash('sha256').update(await readFile(path.join(MODELS_DIR, file))).digest('hex')}',`),
)

await writeFile(OUTPUT, `// Generated by scripts/hash-models.mjs. Do not edit by hand.\nexport const MODEL_HASHES: Record<string, string> = {\n${lines.join('\n')}\n}\n`)
console.log(`Pinned ${files.length} files in ${OUTPUT}`)
